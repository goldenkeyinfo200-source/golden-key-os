export function renderContractHtml(templateHtml, context) {
  const rawHtmlKeys = new Set(['realtorDirectionScope']);

  return String(templateHtml || defaultContractHtml()).replace(
    /\{\{([a-zA-Z0-9_]+)\}\}/g,
    (_match, key) => {
      const value = context[key] ?? '—';
      return rawHtmlKeys.has(key) ? String(value) : escapeHtml(value);
    }
  );
}

