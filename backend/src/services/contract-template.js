export function renderContractHtml(templateHtml, context) {
  return String(templateHtml || defaultContractHtml()).replace(
    /\{\{([a-zA-Z0-9_]+)\}\}/g,
    (_match, key) => escapeHtml(context[key] ?? '—')
  );
}

export function buildContractContext({ contract, caseItem, selectedOffer }) {
  const applicant = caseItem.applicant || {};
  const borrower =
    caseItem.borrowers?.find(
      (item) => item.status === 'APPROVED'
    )?.client ||
    caseItem.borrowers?.[0]?.client ||
    applicant;

  return {
    contractDisplayId: contract.displayId,
    caseDisplayId: caseItem.displayId,
    contractDate: formatDate(contract.createdAt),
    clientFullName: applicant.fullName || '—',
    clientPhone: applicant.phone || '—',
    clientPinfl: applicant.pinfl || '—',
    clientPassport:
      [applicant.passportSeries, applicant.passportNumber]
        .filter(Boolean)
        .join(' ') || '—',
    clientAddress: applicant.address || '—',

    borrowerFullName: borrower.fullName || '—',
    borrowerPhone: borrower.phone || '—',
    borrowerPinfl: borrower.pinfl || '—',
    borrowerPassport:
      [borrower.passportSeries, borrower.passportNumber]
        .filter(Boolean)
        .join(' ') || '—',
    borrowerAddress: borrower.address || '—',

    collateralOwnerFullName:
      caseItem.collateralOwnerFullName || borrower.fullName || '—',
    collateralOwnerPhone:
      caseItem.collateralOwnerPhone || borrower.phone || '—',
    collateralOwnerPinfl:
      caseItem.collateralOwnerPinfl || borrower.pinfl || '—',
    collateralOwnerPassport:
      [
        caseItem.collateralOwnerPassportSeries ||
          borrower.passportSeries,
        caseItem.collateralOwnerPassportNumber ||
          borrower.passportNumber,
      ]
        .filter(Boolean)
        .join(' ') || '—',
    collateralOwnerAddress:
      caseItem.collateralOwnerAddress || borrower.address || '—',

    serviceType:
      SERVICE_LABELS[caseItem.serviceType] || caseItem.serviceType || '—',
    serviceTypeCode: caseItem.serviceType || '',
    realtorBudgetOrPrice: formatMoney(caseItem.requestedAmount),
    requestedAmount: formatMoney(caseItem.requestedAmount),
    approvedAmount: formatMoney(
      selectedOffer?.approvedAmount ?? caseItem.approvedAmount
    ),
    bankName: selectedOffer?.bankName || caseItem.bankName || '—',
    serviceFee: formatMoney(caseItem.serviceFee),
    sellerFullName: escapeHtml(caseItem.sellerFullName || '—'),
    sellerPhone: escapeHtml(caseItem.sellerPhone || '—'),
    sellerPinfl: escapeHtml(caseItem.sellerPinfl || '—'),
    sellerPassport: escapeHtml([caseItem.sellerPassportSeries, caseItem.sellerPassportNumber].filter(Boolean).join(' ') || '—'),
    sellerAddress: escapeHtml(caseItem.sellerAddress || '—'),
    salePropertyType: escapeHtml(caseItem.salePropertyType || '—'),
    salePropertyAddress: escapeHtml(caseItem.salePropertyAddress || '—'),
    saleCadastreNumber: escapeHtml(caseItem.saleCadastreNumber || '—'),
    salePropertyArea: caseItem.salePropertyArea ? `${escapeHtml(caseItem.salePropertyArea)} м²` : '—',
    saleServiceFeePayer: escapeHtml(({BUYER:'Олувчи', SELLER:'Сотувчи', BOTH:'Сотувчи ва Олувчи'})[caseItem.saleServiceFeePayer] || '—'),
  };
}
